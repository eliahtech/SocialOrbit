import 'dotenv/config';
import express from 'express';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {env} from './config.ts';
import {errorHandler} from './http.ts';
import {publicRoutes} from './routes/public.ts';
import {workspacesRoutes} from './routes/workspaces.ts';
import {contentRoutes} from './routes/content.ts';
import {supportRoutes} from './routes/support.ts';
import {analyticsRoutes} from './routes/analytics.ts';
import {notificationsRoutes} from './routes/notifications.ts';
import {automationRoutes} from './routes/automations.ts';
import {mediaRoutes} from './routes/media.ts';
import {clipRoutes} from './routes/clips.ts';
import {designsRoutes} from './routes/designs.ts';
import {aiRoutes} from './routes/ai.ts';
import {billingRoutes} from './routes/billing.ts';
import {socialRoutes,oauthCallbackRoutes} from './routes/social.ts';
import {publishingRoutes} from './routes/publishing.ts';
import {webhookRoutes} from './routes/webhooks.ts';
import {adminRoutes} from './routes/admin.ts';
const app=express();app.disable('x-powered-by');app.set('trust proxy',1);
app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],scriptSrc:["'self'",'https://esm.sh'],styleSrc:["'self'",'https://cdn.jsdelivr.net','https://fonts.googleapis.com',"'unsafe-inline'"],fontSrc:["'self'",'https://fonts.gstatic.com'],imgSrc:["'self'",'data:','https:'],connectSrc:["'self'",'https:','wss:'],objectSrc:["'none'"],baseUri:["'self'"],frameAncestors:["'none'"]}}}));
app.use(express.json({limit:'1mb'}));
app.use('/api',rateLimit({windowMs:60000,limit:90,standardHeaders:'draft-7',legacyHeaders:false}));
app.use('/api',publicRoutes);
app.use('/api/workspaces',workspacesRoutes);
app.use('/api/w/:workspaceId/content',contentRoutes);
app.use('/api/w/:workspaceId/support',supportRoutes);
app.use('/api/w/:workspaceId/analytics',analyticsRoutes);
app.use('/api/w/:workspaceId/automation',automationRoutes);
app.use('/api/w/:workspaceId/media',mediaRoutes);
app.use('/api/w/:workspaceId/clips',clipRoutes);
app.use('/api/w/:workspaceId/designs',designsRoutes);
app.use('/api/w/:workspaceId/ai',aiRoutes);
app.use('/api/w/:workspaceId/billing',billingRoutes);
app.use('/api/w/:workspaceId/social',socialRoutes);
app.use('/api/w/:workspaceId/publishing',publishingRoutes);
app.use('/api/notifications',notificationsRoutes);
app.use('/api/oauth/callback',oauthCallbackRoutes);
app.use('/api/webhooks',webhookRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api',(req,res)=>res.status(404).json({error:'API endpoint not found'}));
app.use(errorHandler);
const publicDir=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../web/public');
app.use(express.static(publicDir,{extensions:['html']}));
app.get('/',(_,res)=>res.sendFile(path.join(publicDir,'index.html')));
app.get('/app',(_,res)=>res.sendFile(path.join(publicDir,'app.html')));
app.get('/billing-return',(_req,res)=>res.redirect(303,'/app.html#billing'));
app.get('/admin',(_,res)=>res.sendFile(path.join(publicDir,'admin.html')));
// No SPA wildcard that could conceal missing static assets as HTTP 200.
app.listen(env.PORT,()=>console.log(`SocialOrbit API running on http://localhost:${env.PORT}`));
